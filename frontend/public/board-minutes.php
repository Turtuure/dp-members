<h3>1. Kokouksen avaaminen</h3>
<p>Puheenjohtaja Samppa Turunen avasi kokouksen klo 18.02.</p>

<h3>2. Kokouksen järjestäytyminen</h3>
<p>Valittiin kokouksen toimihenkilöt:</p>
<ul>
    <li>Puheenjohtaja: Samppa Turunen</li>
    <li>Sihteeri: Markus Avonius</li>
    <li>Pöytäkirjantarkastajat ja ääntenlaskijat: Samppa Turunen ja Markus Avonius</li>
</ul>

<h3>3. Kokouksen laillisuus ja päätösvaltaisuus</h3>
<p>Todettiin kokous sääntöjen mukaisesti kokoon kutsutuksi ja päätösvaltaiseksi. Paikalla olivat yhdistyksen molemmat nykyiset jäsenet.</p>

<h3>4. Esityslistan hyväksyminen</h3>
<p>Hyväksyttiin työjärjestys kokouksen kuluksi.</p>

<h3>5. Vuoden 2025 toimintakertomus, tilinpäätös ja toiminnantarkastajan lausunto</h3>
<p>Esiteltiin vuoden 2025 toimintakertomus. Todettiin, että tilikauden aikana yhdistyksellä ei ollut toimintaa. Käytiin läpi ja vahvistettiin tilinpäätös.</p>

<h3>6. Vastuuvapauden myöntäminen</h3>
<p>Myönnettiin vastuuvapaus hallitukselle ja muille tilivelvollisille vuodelta 2025.</p>

<h3>7. Toimintasuunnitelma, tulo- ja menoarvio sekä jäsenmaksut</h3>
<p>Vahvistettiin kuluvan vuoden toimintasuunnitelma. Kokous keskusteli ja päätti jäsenmaksujen suuruudesta.</p>
<p><strong>Päätös:</strong> Jäsenmaksut vahvistettiin seuraavasti:</p>
<ul>
    <li><strong>Suomalaiset jäsenet:</strong> 5 euroa kuukaudessa (60 euroa vuodessa).</li>
    <li><strong>Tansanialaiset jäsenet:</strong> 1 000 Tansanian shillinkiä (TZS) kuukaudessa (12 000 TZS vuodessa).</li>
</ul>

<h3>8. Hallituksen valinta</h3>
<p>Valittiin hallitukseen kaksi jäsentä: Samppa Turunen ja Markus Avonius.</p>

<h3>9. Toiminnantarkastajien valinta</h3>
<p>Valittiin toiminnantarkastajaksi Jenna Turunen ja varatoiminnantarkastajaksi Katri Viitahalme.</p>

<h3>10. Eronpyynnön käsittely</h3>
<p>Käsiteltiin Sampsa Laineen erohakemus.</p>
<p><strong>Päätös:</strong> Kokous päätti yksimielisesti hyväksyä eronpyynnön ja todettiin Laineen jäsenyyden päättyneeksi.</p>

<h3>11. Uuden jäsenen hyväksyminen</h3>
<p>Käsiteltiin Helen Joseph Turusen jäsenhakemus.</p>
<p><strong>Päätös:</strong> Kokous päätti yksimielisesti hyväksyä Helen Joseph Turusen uudeksi jäseneksi yhdistyksen säännöissä määriteltyjen ehtojen mukaisesti. Jäsenyys alkaa välittömästi kokouksen päätöksestä.</p>

<h3>12. Sääntömuutos, kotipaikan muutos ja yhteystiedot</h3>
<p>Käsiteltiin ehdotus yhdistyksen uusiksi säännöiksi.</p>
<p><strong>Päätös:</strong> Kokous päätti yksimielisesti:</p>
<ul>
    <li>Hyväksyä ja ottaa käyttöön <a href="/bylaws">uudet säännöt</a>.</li>
    <li>Valita yhdistyksen uudeksi kotipaikaksi Vantaa.</li>
    <li>Vahvistaa yhdistyksen uudeksi osoitteeksi Väinö Tannerin tie 15 B 48, 01510 Vantaa.</li>
    <li>Valita yhdistyksen viralliseksi puhelinnumeroksi hallinnollisiin asioihin Markus Avoniuksen numero +358 44 290 2042.</li>
    <li>Vahvistaa yhdistyksen viralliseksi kotisivuksi daems.fi.</li>
    <li>Päivittää nämä tiedot Patentti- ja rekisterihallitukselle (PRH) sääntömuutosilmoituksen yhteydessä.</li>
</ul>

<h3>13. Pankkitilin avaaminen</h3>
<p>
    Kokous käsitteli yhdistyksen maksuliikenteen tehostamista. Nykyiset pankkipalvelut ovat kalliit kansainvälisissä maksuissa ja valuutanvaihdossa.
    Wise on Euroopan talousalueella (EEA) valvottu maksulaitos, joka tarjoaa monivaluuttaista tiliä edullisilla kuluilla ilman kuukausimaksuja.
    Tilin avaamisesta aiheutuu kertaluonteinen 50 &euro; maksu.
</p>
<p><strong>Päätös:</strong> Kokous päättää yksimielisesti avata Wise Business -tilin yhdistyksen virallisessa nimessä DAEM SOCIETY RY, PRH-rekisterinumero 2720636-7. Tilin käyttötarkoitus on yhdistyksen lakisääteinen toiminta: jäsenmaksujen, avustusten ja kansainvälisten maksujen vastaanottaminen ja lähettäminen sekä valuuttatoimintojen hallinta.</p>
<h4>Valtuutus tilin avaamiseen ja käyttöön</h4>
<p>Kokous valtuuttaa seuraavat hallituksen jäsenet edustamaan yhdistystä kaikissa Wise Business -tiliin liittyvissä toimenpiteissä:</p>
<ul>
    <li>Samppa Turunen (puheenjohtaja)</li>
    <li>Markus Avonius (sihteeri / rahastonhoitaja)</li>
</ul>
<p>Valtuutus kattaa:</p>
<ul>
    <li>Tilin avaamisen ja kaikkien tarvittavien dokumenttien toimittamisen Wise:lle.</li>
    <li>Tilin päivittäisen hallinnoinnin, tiimin jäsenten lisäämisen ja käyttöoikeuksien määrittämisen.</li>
    <li>Maksujen hyväksymisen ja korttien (fyysinen + virtuaalinen) tilaamisen.</li>
    <li>Kaikkien muiden tilin käyttöön liittyvien toimien suorittamisen.</li>
</ul>
<p>Maksut yli 500 &euro; vaativat molempien valtuutettujen hyväksynnän. Valtuus on voimassa toistaiseksi, kunnes uusi kokous tai hallitus päättää toisin.</p>
<h4>Riskienhallinta</h4>
<p>Kokous käsitteli Wise-tiliin liittyviä riskejä ja päätti seuraavista toimenpiteistä:</p>
<ul>
    <li>Otetaan käyttöön kaksivaiheinen tunnistautuminen (2FA) kaikille käyttäjille heti tilin avaamisen jälkeen.</li>
    <li>Transaktioita seurataan reaaliaikaisesti Wise-sovelluksessa ja ilmoitetaan koko hallitukselle epäilyttävistä tapahtumista.</li>
    <li>Käyttöoikeudet määritellään minimiperiaatteella. Suuremmat maksut edellyttävät kahden henkilön hyväksyntää.</li>
    <li>Valuuttamääräisiä saldoja pidetään vain tarpeellisen verran.</li>
    <li>Hallitus (valtuutetut henkilöt) raportoi tilin tilasta ja mahdollisista poikkeamista seuraavassa kokouksessa.</li>
    <li>Wise ei ole perinteinen pankki, mutta varat ovat suojattuja valvottujen laitosten erillisillä tileillä. Valmistellaan varasuunnitelma siirtoon perinteiseen pankkiin, jos tarpeen.</li>
</ul>
<p>Kokous katsoo, että näillä toimenpiteillä riskit ovat hallittavissa ja tilin käyttö tukee turvallisesti yhdistyksen toimintaa.</p>

<h3>14. Virallinen jäsenkortti</h3>
<p>Kokous käsitteli ehdotusta yhdistyksen viralliseksi jäsenkortiksi. Esiteltiin uusi jäsenkortti-design.</p>
<p><strong>Päätös:</strong> Kokous päätti yksimielisesti hyväksyä esitellyn designin yhdistyksen viralliseksi jäsenkortiksi.</p>

<h3>15. Palvelimen hankinta</h3>
<p>Kokous käsitteli tarvetta omalle palvelinympäristölle yhdistyksen digitaalisten palveluiden ylläpitämiseksi.</p>
<p><strong>Päätös:</strong> Päätettiin hankkia palvelin yhdistyksen kotisivuja ja sähköpostia varten Hetzner Finland Oy:ltä.</p>

<h3>16. Google Play Store -kehittäjätilin avaaminen</h3>
<p>Kokous keskusteli tarpeesta julkaista yhdistyksen sovelluksia Google Play -kaupassa. Päätettiin yksimielisesti avata yhdistykselle virallinen Google Play Console -kehittäjätili.</p>
<p><strong>Päätös:</strong> Kokous valtuuttaa Markus Avoniuksen avaamaan kehittäjätilin yhdistyksen nimiin, suorittamaan tarvittavan henkilöllisyyden varmennuksen sekä hoitamaan tiliin liittyvän kertaluonteisen rekisteröintimaksun maksamisen yhdistyksen varoista.</p>

<h3>17. Kokouksen päättäminen</h3>
<p>Puheenjohtaja päätti kokouksen klo 20.14.</p>

